'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const read=p=>fs.readFileSync(p,'utf8');
const b={window:{},console};
vm.runInNewContext(read('sim-camera.js'),b,{filename:'sim-camera.js'});
vm.runInNewContext(read('sim-engine.js'),b,{filename:'sim-engine.js'});
const Cam=b.window.BBX_STADIUM_CAMERA,Engine=b.window.BBX_SIM_CORE;
assert.ok(Cam&&Engine);
assert.equal(Engine.STADIUM_ZONES.length,3);
assert.deepEqual(Array.from(Engine.STADIUM_ZONES,k=>k.kind),['over','extreme','over']);
assert.equal(Engine.stadiumPocket(Math.PI/2,'xtreme'),'extreme');
assert.equal(Engine.stadiumPocket(.61,'xtreme'),'over');
assert.equal(Engine.stadiumPocket(Math.PI-.61,'xtreme'),'over');
assert.equal(Engine.stadiumPocket(-.70,'xtreme'),null);
assert.equal(Engine.stadiumPocket(Math.PI/2,'plain'),null);
const pos=Cam.project({yaw:Math.PI/2,elevation:40*Math.PI/180,distance:4});
assert.ok(pos.x>2.9&&Math.abs(pos.z)<.01);
const angles=Array.from({length:9},(_,i)=>Cam.project({yaw:i*Math.PI/4,elevation:40*Math.PI/180,distance:4}));
assert.ok(Math.abs(angles[0].x-angles[8].x)<1e-8);
assert.ok(Math.abs(angles[0].z-angles[8].z)<1e-8);
const listeners=new Map();
const canvas={style:{},attrs:{},
 setAttribute(k,v){this.attrs[k]=v},
 setPointerCapture(){},
 addEventListener(k,fn){(listeners.get(k)||listeners.set(k,[]).get(k)).push(fn)},
 removeEventListener(k,fn){const v=listeners.get(k)||[];const i=v.indexOf(fn);if(i>=0)v.splice(i,1)}
};
const camera={coords:[],position:{set(x,y,z){camera.coords=[x,y,z]}},lookAt(){}};
let frames=0;
const orbit=Cam.create(canvas,camera,()=>frames++);
const fire=(type,values={})=>{for(const fn of listeners.get(type)||[])fn({pointerId:1,pointerType:'touch',button:0,clientX:0,clientY:0,deltaY:0,preventDefault(){},...values})};
const original=orbit.getState();
fire('pointerdown',{clientX:100,clientY:100});
fire('pointermove',{clientX:885,clientY:100});
assert.ok(orbit.getState().yaw>6,'one finger must travel through at least 360 degrees');
fire('pointermove',{clientX:885,clientY:-999});
assert.ok(orbit.getState().elevation>=Cam.limits.minElevation,'cannot orbit beneath the board');
fire('pointerup');
orbit.preset('reset');
assert.equal(orbit.getState().distance,original.distance);
fire('pointerdown',{pointerId:1,clientX:100,clientY:100});
fire('pointerdown',{pointerId:2,clientX:200,clientY:100});
fire('pointermove',{pointerId:2,clientX:300,clientY:100});
assert.ok(orbit.getState().distance<original.distance,'pinch out zooms in');
fire('pointerup',{pointerId:1});
fire('pointerup',{pointerId:2});
fire('wheel',{deltaY:15000});
assert.equal(orbit.getState().distance,Cam.limits.maxDistance);
fire('wheel',{deltaY:-15000});
assert.equal(orbit.getState().distance,Cam.limits.minDistance);
orbit.preset('top');
assert.ok(orbit.getState().elevation>1.38,'top preset approaches top-down');
orbit.preset('front');
assert.ok(orbit.getState().elevation<.60,'front preset has low viewing angle');
orbit.preset('reset');
assert.equal(orbit.getState().yaw,0);
assert.ok(frames>5);
orbit.destroy();
assert.equal((listeners.get('pointermove')||[]).length,0,'unmount cleans up listeners');
const scene=read('sim-view.js'),html=read('index.html');
assert.ok(scene.includes('new T.LatheGeometry('),'curved 3D battle bowl');
assert.ok(scene.includes('new T.ExtrudeGeometry(hull,'),'polygon chassis');
assert.ok(scene.includes('new T.ShapeGeometry(hull,'),'translucent cover');
assert.ok(scene.includes('new T.TubeGeometry(railCurve,'),'3D curved rail');
assert.ok(scene.includes('new T.InstancedMesh('),'gear teeth');
assert.ok(scene.includes('const zones=root.BBX_SIM_CORE?.STADIUM_ZONES'),'pockets share simulated zone angles');
assert.ok(html.indexOf('sim-camera.js')<html.indexOf('sim-view.js'),'script loading order');
assert.ok(html.includes('id="simCameraTop"')&&html.includes('id="simCameraFront"')&&html.includes('id="simCameraReset"'));
console.log('360-degree orbit, mobile pinch, wheel zoom, view presets, official pocket sectors verified');

'use strict';
const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const read=p=>fs.readFileSync(p,'utf8');
const ctx={window:{}};vm.runInNewContext(read('sim-quality.js'),ctx,{filename:'sim-quality.js'});
const Q=ctx.window.BBX_SIM_QUALITY;
assert.ok(Q&&Q.profiles&&Q.defaultMode==='ultra');
assert.deepEqual(Object.keys(Q.profiles).sort(),['balanced','performance','ultra'].sort());
assert.equal(Q.normalize('ultra'),'ultra');
assert.equal(Q.normalize('INVALID'),'ultra');
assert.equal(Q.normalize('__proto__'),'ultra');
const p=Q.profile('performance'),b=Q.profile('balanced'),u=Q.profile('ultra');
assert.equal(u.id,'ultra');
assert.ok(p.pixelRatio<b.pixelRatio&&b.pixelRatio<u.pixelRatio);
assert.ok(!p.shadows&&b.shadows&&u.shadows);
assert.equal(p.shadowSize,0);
assert.equal(b.shadowSize,512);
assert.equal(u.shadowSize,2048);
assert.ok(p.sparkBudget<b.sparkBudget&&b.sparkBudget<u.sparkBudget);
assert.ok(p.trailLimit<b.trailLimit&&b.trailLimit<u.trailLimit);
assert.equal(p.contactShadow,false);
assert.equal(u.contactShadow,true);
assert.equal(p.spinBlur,false);
assert.equal(b.spinBlur,false);
assert.equal(u.spinBlur,true);
assert.ok(p.clearcoat<b.clearcoat&&b.clearcoat<u.clearcoat);
assert.equal(u.toneMapping,true);
assert.equal(Q.resolutionScale('ultra',3),2);
assert.equal(Q.resolutionScale('ultra',1),1);
assert.equal(Q.resolutionScale('performance',3),.85);
const code=read('sim-view.js'),ui=read('sim-ui.js'),html=read('index.html');
const includes=(snippet,description)=>assert.ok(code.includes(snippet),description);
includes('function setQuality(mode)','live setter must exist');
includes('renderer.setPixelRatio(dpr)','pixel density must really change');
includes('renderer.shadowMap.enabled=quality.shadows','shadows must actually toggle');
includes('lights.key.castShadow=quality.shadows','castShadow must follow quality');
includes('lights.key.shadow.mapSize.set(size,size)','shadow map resolution must change');
includes('THREE.ACESFilmicToneMapping','ACES color toning must apply');
includes('quality.hemisphere','lighting must be quality dependent');
includes('new THREE.MeshPhysicalMaterial(','blade should use physical metal material');
includes('new T.MeshPhysicalMaterial(','stadium clear guard should use physical material');
includes('quality?.contactShadow','contact shadow must actually render');
includes('quality?.spinBlur','spin blur must depend on the selected profile');
includes('quality?.sparkBudget','impact spark count must be quality dependent');
includes('points.slice(-quality.trailLimit)','motion trails must adapt');
includes('g.traverse(obj=>{','newly assembled tops must receive active material quality');
includes('setQuality,getQuality:()=>qualityMode','quality must be exposed by the view');
assert.ok(ui.includes("const qualityKey='bbx-render-quality-v1'"));
assert.ok(ui.includes("root.localStorage?.setItem(qualityKey,mode)"));
assert.ok(!ui.slice(ui.indexOf('function syncQuality('),ui.indexOf("qualityInput?.addEventListener('change'")).includes('clearMatch('),
 'quality changes cannot clear battle');
assert.ok(html.includes('id="simQuality"'));
assert.ok(html.includes('value="ultra" selected'));
assert.ok(html.indexOf('sim-quality.js')<html.indexOf('sim-view.js'));
assert.ok(html.indexOf('sim-view.js')<html.indexOf('sim-ui.js'));
const paths=read('.github/workflows/simulator-smoke.yml');
assert.ok(paths.includes('node tests/sim-quality-smoke.cjs'));
assert.ok(paths.includes('node --check sim-quality.js'));
console.log('Performance/balanced/ultra shader, resolution, shadow, FX, UI and persistence contracts verified');

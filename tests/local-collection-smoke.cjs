'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const read=p=>fs.readFileSync(p,'utf8');
const sandbox={window:{}};
vm.runInNewContext(read('collection-local.js'),sandbox);
const L=sandbox.window.BBX_LOCAL;
assert.ok(L&&L.parseBackup&&L.sanitizeAbility);
const a=L.sanitizeBey({id:'LOCAL-123456-example',name:'Left Test',system:'UX',
 ownMarket:'JP',spinDirection:'L',blade:'Example Blade',ratchet:'3-60',bit:'F'});
assert.equal(a.spinDirection,'L');
assert.equal(a.packageId,'PKG-LOCAL-123456-example');
assert.equal(L.makePackage(a).market,'JP');
assert.equal(L.makePackage(a).manufacturer,'Takara Tomy');
assert.throws(()=>L.sanitizeBey({...a,spinDirection:'X'}),/方向/);
assert.throws(()=>L.sanitizeBey({...a,ratchet:'bad'}),/規格/);
assert.throws(()=>L.sanitizeBey({...a,id:'OWN-G3084-01'}),/編號/);
const cx=L.sanitizeBey({id:'LOCAL-999-CX',name:'CX Trial',system:'CX',ownMarket:'US',spinDirection:'R',
 blade:'Trial',lockChip:'Trial Chip',mainBlade:'Trial Main',assistBlade:'Trial Assist',ratchet:'7-60',bit:'T'});
assert.equal(cx.mainBlade,'Trial Main');
const record=L.sanitizeAbility(a.id,'bit',{type:'attack',stats:{attack:30,defense:10,stamina:20,dash:50,burst:70},sourceUrl:'https://example.com'},a);
assert.equal(record.verification.status,'user-entered-unverified');
assert.equal(record.stats.dash,50);
assert.equal(record.stats.height,0);
assert.equal(L.sanitizeAbility(a.id,'ratchet',{type:'balance',stats:{attack:10,defense:10,stamina:10,dash:0,burst:0}},a).stats.height,60);
assert.throws(()=>L.sanitizeAbility(a.id,'bit',{type:'attack',stats:{attack:30,defense:10,stamina:20,dash:NaN,burst:70}},a),/能力/);
assert.throws(()=>L.sanitizeAbility(a.id,'bit',{type:'attack',stats:{attack:30,defense:10,stamina:20,dash:50,burst:70},sourceUrl:'javascript:evil'},a),/HTTPS/);
const slots=()=>Array.from({length:3},()=>({mode:'whole',blade:'',ratchet:'',bit:'',chip:'',main:'',assist:''}));
const saved={format:'BBX-966-BACKUP',version:2,additions:[a],decks:[{id:'D-1',name:'test',slots:slots()}],slots:slots(),
 customAbilities:{[a.id]:{id:a.id,parts:{bit:record}}}};
const imported=L.parseBackup(saved,['OWN-G3084-01']);
assert.equal(imported.additions.length,1);
assert.equal(imported.packages.length,1);
assert.equal(imported.decks.length,1);
assert.equal(imported.customAbilities[a.id].parts.bit.stats.dash,50);
assert.equal(L.parseBackup({...saved,version:1,customAbilities:null},[]).additions.length,1);
assert.equal(L.parseBackup(saved,[a.id]).additions.length,0,'published imports cannot be duplicated');
assert.throws(()=>L.parseBackup({...saved,additions:[a,a]},[]),/重複/);
assert.throws(()=>L.parseBackup({...saved,slots:[{mode:'evil'}]},[]),/槽/);
assert.throws(()=>L.parseBackup({...saved,customAbilities:{[a.id]:{parts:{bit:{stats:{attack:0}}}}}},[]),/能力/);
const app=read('app.js'),html=read('index.html'),work=read('.github/workflows/import-collected-top.yml');
assert.ok(html.includes('id="manualAbilityForm"')&&html.includes('id="syncSubmit"'));
assert.ok(html.indexOf('collection-local.js')<html.indexOf('app.js'));
assert.ok(app.includes('function renderManualAbilityOptions()')&&app.includes("window.BBX_PART_STATS.beys[b.id]=entry"));
assert.ok(app.includes("DB.packages.push(...result.packages)")&&app.includes("L.parseBackup(raw,seedIds)"));
assert.ok(app.includes("new Event('bbx-inventory-updated')"));
assert.ok(work.includes("github.event.issue.user.login == github.repository_owner"),'GitHub writes must require owner');
assert.ok(work.includes('pulls.create'),'GitHub sync should create a reviewable PR');
assert.ok(!app.includes('GITHUB_TOKEN')&&!app.includes('ghp_'),'never embed GitHub token in public JS');
console.log('Validated strict backup migration, manual spin/CX/ratings, published-record dedupe and owner-reviewed PR sync');
